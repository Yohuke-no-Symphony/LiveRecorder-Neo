using Spectre.Console;

namespace Yohuke.LiveRecorder.Transcoding.Worker.Configuration;

internal static class WorkerConnectionSetup
{
    internal static WorkerConnectionOptions Configure(WorkerConnectionOptions current, string title)
    {
        RequireInteractive();
        AnsiConsole.MarkupLine("[bold]" + Markup.Escape(title) + "[/]");
        var apiBaseUrl = Text("Server URL (HTTP or HTTPS)", current.ApiBaseUrl).Trim();
        var apiUri = new Uri(apiBaseUrl, UriKind.Absolute);
        var result = current with
        {
            ApiBaseUrl = apiBaseUrl,
            ControlHost = Text("TCP control host", apiUri.IdnHost).Trim(),
            ControlPort = Integer("TCP control port", current.ControlPort, 1, 65535),
            ControlUseTls = AnsiConsole.Confirm("Use TLS for the TCP control connection?", apiUri.Scheme == Uri.UriSchemeHttps),
            WorkerId = Text("Worker ID generated by the server", current.WorkerId).Trim()
        };
        var preserveSecret = result.WorkerId == current.WorkerId && result.ControlHost == current.ControlHost
            && result.ControlPort == current.ControlPort && result.ApiBaseUrl == current.ApiBaseUrl
            && !string.IsNullOrWhiteSpace(current.Secret);
        var secretPrompt = new TextPrompt<string>(preserveSecret ? "Worker secret (leave empty to keep the current secret)" : "Worker secret generated by the server")
            .Secret().HideDefaultValue().Validate(value => value.Length <= 256 && (preserveSecret || !string.IsNullOrWhiteSpace(value)));
        if (preserveSecret)
        {
            secretPrompt.AllowEmpty();
        }
        var secret = AnsiConsole.Prompt(secretPrompt);
        result.Secret = preserveSecret && string.IsNullOrWhiteSpace(secret) ? current.Secret : secret;
        if ((result.ControlUseTls || apiUri.Scheme == Uri.UriSchemeHttps)
            && AnsiConsole.Confirm("Configure a TLS server name or private certificate fingerprints?", false))
        {
            result.TlsServerName = ConnectionText("TLS control server name", current.TlsServerName);
            result.ServerCertificateSha256 = ConnectionText("Shared certificate SHA-256 fingerprint", current.ServerCertificateSha256);
            result.ControlCertificateSha256 = ConnectionText("TCP control certificate SHA-256 fingerprint", current.ControlCertificateSha256);
            result.ApiCertificateSha256 = ConnectionText("HTTPS certificate SHA-256 fingerprint", current.ApiCertificateSha256);
        }
        result.Validate();
        return result;
    }

    private static void RequireInteractive()
    {
        if (Console.IsInputRedirected || !AnsiConsole.Profile.Capabilities.Interactive)
        {
            throw new InvalidOperationException("This command requires an interactive terminal. Run 'register' or 'config' interactively, or prepare the settings file selected by --config.");
        }
    }

    private static string Text(string title, string value)
    {
        var prompt = new TextPrompt<string>(title).Validate(input => !string.IsNullOrWhiteSpace(input));
        if (!string.IsNullOrWhiteSpace(value))
        {
            prompt.DefaultValue(value);
        }
        return AnsiConsole.Prompt(prompt);
    }

    private static string? ConnectionText(string title, string? current)
    {
        var input = AnsiConsole.Prompt(new TextPrompt<string>(title + (string.IsNullOrEmpty(current)
            ? " (leave empty to keep unset)" : " (leave empty to keep, enter - to clear)")).AllowEmpty());
        return input.Trim() switch
        {
            "-" => null,
            "" => current,
            var value => value
        };
    }

    private static int Integer(string title, int value, int minimum, int maximum) => AnsiConsole.Prompt(new TextPrompt<int>(title)
        .DefaultValue(value).Validate(input => input >= minimum && input <= maximum));

}
